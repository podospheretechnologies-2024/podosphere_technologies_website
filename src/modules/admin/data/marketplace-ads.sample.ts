function withCampaignTotals(snapshot: MarketplaceSnapshot): MarketplaceSnapshot {
  const sum = (pick: (row: MarketplaceCampaign) => number) =>
    snapshot.campaigns.reduce((total, row) => total + pick(row), 0);
  const spend = sum((row) => row.spend);
  const revenue = sum((row) => row.revenue);
  const impressions = sum((row) => row.impressions);
  const clicks = sum((row) => row.clicks);
  const orders = sum((row) => row.orders);
  const live = snapshot.campaigns.filter((row) => row.status === 'LIVE').length;
  const derived: Record<string, string> = {
    Live: String(live),
    'Avg ROI': spend > 0 ? (revenue / spend).toFixed(2) : '0.00',
    CTR: impressions > 0 ? `${((clicks / impressions) * 100).toFixed(2)}%` : '0.00%',
    CVR: clicks > 0 ? `${((orders / clicks) * 100).toFixed(2)}%` : '0.00%',
    'Avg CPC': clicks > 0 ? `₹${(spend / clicks).toFixed(2)}` : '₹0.00',
    'Units sold': String(orders),
    Conversions: String(orders),
  };
  return {
    ...snapshot,
    extras: snapshot.extras.map((extra) => ({ ...extra, value: derived[extra.label] ?? extra.value })),
    kpis: {
      spend,
      revenue,
      roas: spend > 0 ? Math.round((revenue / spend) * 100) / 100 : 0,
      impressions,
      clicks,
      orders,
    },
  };
}

