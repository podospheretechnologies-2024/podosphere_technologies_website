export function pickMarketplaceClients(rows: MarketplaceClientOption[]): MarketplaceClientOption[] {
  const unused = [...rows];
  return PREFERRED_SAMPLE_CLIENTS.map((pref, index) => {
    const matchIndex = unused.findIndex((row) => pref.match.test(row.name));
    if (matchIndex >= 0) {
      const [found] = unused.splice(matchIndex, 1);
      return found;
    }
    return {
      id: `demo-${index + 1}`,
      name: pref.name,
      organizationName: 'Sample',
      isDemo: true,
    };
  });
}

export function padMarketplaceClients(rows: MarketplaceClientOption[]): MarketplaceClientOption[] {
  return pickMarketplaceClients(rows);
}

function withCampaignTotals(snapshot: MarketplaceSnapshot): MarketplaceSnapshot {
  const sum = (pick: (row: MarketplaceCampaign) => number) =>
    snapshot.campaigns.reduce((total, row) => total + pick(row), 0);
  const spend = sum((row) => row.spend);
  const revenue = sum((row) => row.revenue);
  return {
    ...snapshot,
    kpis: {
      spend,
      revenue,
      roas: spend > 0 ? Math.round((revenue / spend) * 100) / 100 : 0,
      impressions: sum((row) => row.impressions),
      clicks: sum((row) => row.clicks),
      orders: sum((row) => row.orders),
    },
  };
}

export function snapshotFor(slot: number, marketplace: MarketplaceId): MarketplaceSnapshot {
  const index = Math.min(Math.max(slot, 0), MARKETPLACE_CLIENT_SLOTS - 1);
  if (marketplace === 'meta') {
    const meta = withCampaignTotals(META_SAMPLE[index]);
    const live = meta.campaigns.filter((row) => row.status === 'LIVE').length;
    const { spend, orders } = meta.kpis;
    return {
      ...meta,
      extras: [
        { label: 'Active', value: String(live) },
        { label: 'Leads', value: String(orders) },
        { label: 'CPL', value: orders > 0 ? `₹${Math.round(spend / orders)}` : '—' },
      ],
    };
  }
  return withCampaignTotals(MARKETPLACE_SAMPLE[index][marketplace]);
}
