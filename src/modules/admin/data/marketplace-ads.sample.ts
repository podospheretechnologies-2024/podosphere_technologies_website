function metaCampaign(
  id: string,
  name: string,
  type: string,
  status: CampaignStatus,
  budgetLabel: string,
  spend: number,
  impressions: number,
  clicks: number,
  orders: number,
): MarketplaceCampaign {
  const revenue = orders > 0 ? Math.round(spend * (orders > 4 ? 1.8 : 1.2)) : 0;
  return {
    id,
    name,
    type,
    status,
    duration: 'No end date',
    budgetLabel,
    spend,
    impressions,
    clicks,
    orders,
    revenue,
    roas: spend > 0 && revenue > 0 ? revenue / spend : 0,
  };
}

