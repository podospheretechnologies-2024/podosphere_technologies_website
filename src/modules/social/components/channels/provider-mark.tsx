const brands: Record<
  string,
  { className: string; Icon: (props: { className?: string }) => ReactElement }
> = {
  linkedin: { className: 'bg-[#0a66c2]', Icon: LinkedInIcon },
  facebook: { className: 'bg-[#1877f2]', Icon: FacebookIcon },
  instagram: {
    className: 'bg-[linear-gradient(45deg,#f9ce34,#ee2a7b_50%,#6228d7)]',
    Icon: InstagramIcon,
  },
};

// Brand-coloured tile for a platform; unknown platforms fall back to their initial.
export function ProviderMark({ identifier, name, size = 'md', className }: ProviderMarkProps) {
  const brand = brands[identifier];
  const Icon = brand?.Icon;

  return (
    <span
      aria-hidden
      className={cn(
        'flex shrink-0 items-center justify-center font-bold text-white',
        brand?.className ?? 'bg-primary',
        sizeClasses[size],
        className
      )}
    >
      {Icon ? (
        <Icon className={iconSizeClasses[size]} />
      ) : (
        <span className={size === 'sm' ? 'text-[10px]' : 'text-base'}>
          {name.charAt(0).toUpperCase()}
        </span>
      )}
    </span>
  );
}
